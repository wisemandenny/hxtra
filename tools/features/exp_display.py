"""EXP display: EXP 1 and EXP 2 as bars and values on the Home screen (src/m4/exp_display.s, docs/research/features/exp-display.md)."""
import struct

import image_store
from features import Setting, gr

FLAG = 'HX_EXP_DISPLAY'
MENU = 'Displays'
ORDER = 115                         # after gr, whose LAYOUT it reads, and after preset_color, so Preset LED Color keeps its page
MODULE = 'src/m4/exp_display.s'
SOURCES = (b'Off', b'EXP 1', b'EXP 2')
SETTINGS = (
    Setting('left', b'Left\nHome EXP', SOURCES),
    Setting('right', b'Right\nHome EXP', SOURCES),
)

PEDAL_LIT, PEDAL_LISTENER = 0x28d96d7c, 0x28d947d1
REDRIVE_CALLS, CONTROLLER_SET = (0x28de12ba, 0x28de1282), 0x28dde408
RESTORE_CALLS, CONTROLLER_RESTORE = (0x28deb2aa, 0x28deb8fe), 0x28de0f24    # a preset load's controller restore, from a buffer or a file
SELECT, SELECT_STOCK = 0x28de2f90, bytes.fromhex('2de9 f04f')                # snapshot select; push.w {r4-r11,lr}
LED_TICK_CALL, LED_SLEEP = 0x28db7f44, 0x28e24c58
HOME_PAINT_LIT, HOME_PAINT = 0x28d96e28, 0x28dc8d39
TOP_PAINT_LIT, TOP_PAINT = 0x28d96d90, 0x28dca359

FONTS = (b'hx28_boldFont', b'hx21_regularFont')    # the value's, and the smaller one under the GR meter at Middle where it would not clear
FONT_NUMBERS = {b'hx21_regularFont': 1, b'hx28_boldFont': 2}
CHARS = '0123456789-'
LABEL_ROW, LABEL_W = 146, 30
CLEARANCE = 2                       # the value's lowest row at least this many rows above the GR band's top row
AREA = (120, 66, 253)               # the free sides of the signal flow: from row 120 up, x up to 66 and from 253


def metrics(e7, e8, font):
    """(the width of each of CHARS, font's spacing, the lowest and highest row their pixels take in the cell)."""
    count, table = image_store.font(e7, font)
    spacing = struct.unpack_from('<I', e7, image_store.record(e7, font) + 20)[0]
    widths, rows = [], set()
    for c in CHARS:
        h, w, item = image_store.glyph(e7, table, ord(c))
        if item == image_store.EMPTY_GLYPH:
            raise SystemExit(f'exp_display: {font.decode()} has no {c!r}')
        off, _ = image_store.item(e8, item)
        px = struct.unpack_from(f'<{w * h}H', e8, off)
        widths.append(w)
        rows |= {y for y in range(h) if any(px[x * h + y] for x in range(w))}
    return widths, spacing, (min(rows), max(rows))


def fonts(e7, e8):
    """Per font of FONTS: (font number, widths, spacing, the cell's row, the lowest row of its pixels), its highest row of pixels
    one row clear of the label."""
    out = []
    for font in FONTS:
        widths, spacing, (low, high) = metrics(e7, e8, font)
        y = LABEL_ROW - 2 - high
        out.append((FONT_NUMBERS[font], widths, spacing, y, y + low))
    return out


def width(widths, spacing, text):
    return sum(widths[CHARS.index(c)] for c in text) + spacing * (len(text) - 1)


def small_from(big_low, small_low):
    """The smallest Mtr Size at Middle whose band the big font would not clear by CLEARANCE rows (255: none)."""
    sizes = [t for t in gr.SIZES if big_low - gr.middle_rows(t)[1] < CLEARANCE]
    for t in sizes:
        top = gr.middle_rows(t)[1]
        if small_low - top < CLEARANCE:
            raise SystemExit(f'exp_display: at GR Middle {t} px the band reaches row {top}, and the small value font starts at row '
                             f'{small_low} under the label at rows {LABEL_ROW}..155: under {CLEARANCE} rows clear')
    return sizes[0] if sizes else 255


def inc(e7, e8, meter=None):
    (big_font, big_w, big_sp, big_y, big_low), (small_font, small_w, small_sp, small_y, small_low) = fonts(e7, e8)
    box_w = max(width(big_w, big_sp, '100'), width(small_w, small_sp, '100'), LABEL_W)
    if min(big_low, small_low) < AREA[0] or max(gr.SIZES) + 1 + box_w > AREA[1] or 319 - max(gr.SIZES) - 1 - box_w < AREA[2]:
        raise SystemExit(f'exp_display: a readout {box_w} px wide from row {min(big_low, small_low)} leaves the sides of the signal flow')
    shown, layout = (meter['data'] + gr.SHOWN, meter['data'] + gr.LAYOUT) if meter else (0, 0)
    rows = [f'    .byte {", ".join(map(str, w))}, {sp}, {font}, {y}, {low}, 0\n'
            for font, w, sp, y, low in ((big_font, big_w, big_sp, big_y, big_low), (small_font, small_w, small_sp, small_y, small_low))]
    return {'exp.inc': '@ exp.inc - generated by tools/features/exp_display.py from the stock Entries 7 and 8\n'
                       f'.equ GR_SHOWN, {shown:#x}\n.equ GR_LAYOUT, {layout:#x}\n.equ SMALL_FROM, {small_from(big_low, small_low)}\n'
                       f'.equ LABEL_ROW, {LABEL_ROW}\n.equ LABEL_W, {LABEL_W}\n.equ BOX_W, {box_w}\n'
                       '.macro FONTS                    @ big, small: widths of 0..9 and -, spacing, font, cell row, lowest row, 0\n'
                       f'{"".join(rows)}.endm\n'}


def apply(p):
    m = p.module(MODULE, inc(p.entry(7).data, p.entry(8).data, p.modules.get(gr.MODULE)))
    p.chain_ptr(PEDAL_LIT, PEDAL_LISTENER, before=m['exp_event'])   # before: the learn the listener ends in clears the Learn byte
    for site in REDRIVE_CALLS:
        p.chain_bl(site, CONTROLLER_SET, after=m['exp_redrive'])
    for site in RESTORE_CALLS:
        p.chain_bl(site, CONTROLLER_RESTORE, before=m['exp_loaded'])  # before: the restore's re-drive under Global clears its mark
    p.chain_entry(SELECT, SELECT_STOCK, after=m['exp_recalled'])
    p.chain_bl(LED_TICK_CALL, LED_SLEEP, after=m['exp_tick'])
    p.chain_ptr(HOME_PAINT_LIT, HOME_PAINT, before=m['exp_home_before'], after=m['exp_home_after'])
    p.chain_ptr(TOP_PAINT_LIT, TOP_PAINT, before=m['exp_top_before'], after=m['exp_top_after'])
