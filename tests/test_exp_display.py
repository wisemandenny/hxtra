def assert_bar(d, x0, lo, hi, v=None, colour=None):
    """The bar at x0 over rows lo..hi: v's fill in colour over a dark track with ticks, or with v None an empty outline in colour,
    grey by default."""
    h = hi - lo + 1
    ticks = {rows(25, h), rows(50, h), rows(75, h)}
    for (x, y), got in d.at(range(x0, x0 + 6), range(lo, hi + 1)).items():
        if v is None:
            want = (colour or GREY) if x in (x0, x0 + 5) or y in (lo, hi) else 0
        else:
            want = colour if y - lo < rows(v, h) else TICK if y - lo in ticks else TRACK
        assert got == want, (x, y)


def assert_readout(d, side, text, colour, label, tl=1, tr=318, font=BIG):
    """The readout's 44 px wide box: the label's 3x5 glyphs at 2x at rows 146..155, the value in font under it with its highest row
    of pixels at 144, both in colour."""
    box = range(tl, tl + BOX_W) if side == 0 else range(tr - BOX_W + 1, tr + 1)
    first = box.start + (0 if side == 0 else BOX_W - 30)
    lab = label_pixels(label, first)
    for (x, y), got in d.at(box, range(146, 156)).items():
        assert got == (colour if (x, y) in lab else 0), (x, y)
    x = tl if side == 0 else tr + 1 - width(text, font)
    assert (text, x, cell(font), font.number, colour, 0, 1) in d.texts


