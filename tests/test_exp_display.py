def screen(pos=None, t=0, text='50'):
    """Every pixel the display leaves lit with both sides live at text beside the meter at pos and t: the bars' columns over their
    rows, the labels and the values, so a pixel left over from an earlier place or font shows as a difference."""
    lx, rx, lo, hi, tl, tr = spec(pos, t)
    font, w = font_for(pos, t), width(text, font_for(pos, t))
    out = {(x, y) for x0 in (lx, rx) for x in range(x0, x0 + 6) for y in range(lo, hi + 1)}
    out |= label_pixels('EXP1', tl) | label_pixels('EXP2', tr - 29)
    return out | {(x, y) for x in (*range(tl, tl + w), *range(tr + 1 - w, tr + 1)) for y in range(low(font), 145)}


