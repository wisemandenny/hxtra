Font = namedtuple('Font', 'number widths spacing ink')      # the text renderer's font k, 0..9 and -, spacing, rows of pixels in the cell
BIG = Font(2, [15, 8, 13, 13, 14, 13, 14, 13, 14, 14, 13], 3, (5, 25))     # hx28_boldFont, as the stock file has it
SMALL = Font(1, [10, 5] + [10] * 9, 3, (4, 19))                            # hx21_regularFont
BOX_W, SMALL_FROM = 44, 15
