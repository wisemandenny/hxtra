# --- stale: after a preset load or a snapshot recall under EXP Position Preset or Snapsht, until the next event ---

def test_the_load_and_recall_hooks_only_mark_both_controllers(d):
    """Before a preset load's controller restore (0x28deb2aa, 0x28deb8fe) and after a snapshot select (0x28de2f90): a byte per
    controller and kind, and DIRTY, as plain stores. An event (or a re-drive) clears its controller's marks."""
    d.call('exp_loaded', CTRLS, 0, 0, 0)
    assert not d.m.log
    assert (d.word(CHANGED), d.word(CHANGED + 4), d.word(DIRTY)) == (1, 1, 1)
    d.word(DIRTY, 0)
    d.call('exp_recalled', 0x2812c630, 1, 0, 0)
    assert not d.m.log
    assert (d.word(CHANGED), d.word(CHANGED + 4), d.word(DIRTY)) == (0x101, 0x101, 1)
    d.event(1, 0.4)
    assert (d.word(CHANGED), d.word(CHANGED + 4)) == (0x101, 0)
    d.redrive(1, 0.4)
    assert (d.word(CHANGED), d.word(CHANGED + 4)) == (0, 0)


