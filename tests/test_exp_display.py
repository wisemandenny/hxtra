def chains_of(env, monkeypatch, owned=None):
    seen, modules = {}, {}
    real_finish, real_module = pm.Patch.finish_chains, pm.Patch.module

    def finish(self):
        seen.update({site: [list(x) if isinstance(x, list) else x for x in c] for site, c in self.chains.items()})
        if owned is not None:
            owned.update(self.owned)
        return real_finish(self)

    def module(self, path, inc=None):
        modules[path] = (real_module(self, path, inc), inc)
        return modules[path][0]
    monkeypatch.setattr(pm.Patch, 'finish_chains', finish)
    monkeypatch.setattr(pm.Patch, 'module', module)
    menu_entry0(stock_e0(), None, env)
    return seen, modules


@pytest.mark.firmware
def test_a_build_with_every_m4_feature_shares_the_hooks(monkeypatch):
    """Every feature with a switch at once: no two take one site in different ways, and the display draws after the GR meter. The
    listener's handler runs before it: its learn (0x28ddf6dc) clears the Learn byte for controllers 1 and 2 (0x28ddf6fc), so after
    the listener the byte always reads 0."""
    env = {f: '1' for m in features.load() for f in features.flags(m)}
    chains, modules = chains_of(env, monkeypatch)
    m = modules[ed.MODULE][0]
    _, _, before, after, owners = chains[ed.HOME_PAINT_LIT]
    assert m['exp_home_before'] in before and m['exp_home_after'] in after
    assert owners.index('gr') < owners.index('exp_display')
    assert after.index(modules[gr.MODULE][0]['draw']) < after.index(m['exp_home_after'])
    assert chains[ed.TOP_PAINT_LIT][2:4] == [[m['exp_top_before']],
                                             [modules['src/m4/more_snapshots.s'][0]['snaps_paint'], m['exp_top_after']]]
    assert chains[ed.PEDAL_LIT] == ['ptr', ed.PEDAL_LISTENER, [m['exp_event']], [], ['exp_display']]
    for site in ed.REDRIVE_CALLS:
        assert chains[site] == ['bl', ed.CONTROLLER_SET, [], [m['exp_redrive']], ['exp_display']]
    for site in ed.RESTORE_CALLS:
        assert chains[site] == ['bl', ed.CONTROLLER_RESTORE, [m['exp_loaded']], [], ['exp_display']]
    kind, stock, _, after, owners = chains[ed.SELECT]
    assert (kind, stock) == ('entry', ed.SELECT_STOCK) and m['exp_recalled'] in after and 'exp_display' in owners
    assert m['exp_tick'] in chains[ed.LED_TICK_CALL][3]
    assert modules[ed.MODULE][1] == exp_inc(modules[gr.MODULE][0]['data']), "the GR meter's shown and layout words"


