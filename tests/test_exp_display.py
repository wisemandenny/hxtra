def cell(font):
    """The row the value's cell starts on: its highest row of pixels at 144, one row under the label."""
    return 144 - font.ink[1]


def low(font):
    return cell(font) + font.ink[0]


def exp_inc(gr_data=0):
    shown, layout = (gr_data + gr.SHOWN, gr_data + gr.LAYOUT) if gr_data else (0, 0)
    rows = ''.join(f'    .byte {", ".join(map(str, f.widths))}, {f.spacing}, {f.number}, {cell(f)}, {low(f)}, 0\n' for f in (BIG, SMALL))
    return {'exp.inc': '@ exp.inc - generated by tools/features/exp_display.py from the stock Entries 7 and 8\n'
                       f'.equ GR_SHOWN, {shown:#x}\n.equ GR_LAYOUT, {layout:#x}\n.equ SMALL_FROM, {SMALL_FROM}\n'
                       f'.equ LABEL_ROW, 146\n.equ LABEL_W, 30\n.equ BOX_W, {BOX_W}\n'
                       '.macro FONTS                    @ big, small: widths of 0..9 and -, spacing, font, cell row, lowest row, 0\n'
                       f'{rows}.endm\n'}


def f2u(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]


def percent(x):
    """round(x * 100), halves up, of the float32 x, as the display shows it."""
    v = Fraction(struct.unpack('<f', struct.pack('<f', abs(x)))[0]) * 100
    return min(100, int(v + Fraction(1, 2)))


def rows(v, h):
    return (v * h + 50) // 100


def width(s, font=BIG):
    return sum(font.widths[10 if c == '-' else int(c)] for c in s) + font.spacing * (len(s) - 1)


def spec(pos=None, t=0):
    """(left bar's x, right bar's x, the bars' rows of 0 and 100, the left readout's first x, the right readout's last x)."""
    lx, rx, lo, hi, tl, tr = 0, 314, 0, 116, 1, 318
    if pos == 'Bottom':
        lo = t + 1
    if pos == 'Left':
        lx, tl = t + 1, t + 2
    if pos == 'Right':
        rx, tr = 313 - t, 318 - t - 1
    if pos == 'Middle':
        hi = 118 - t // 2 - 2
    return lx, rx, lo, hi, tl, tr


def gr_area(pos, t):
    """Every pixel the GR meter's lights can cover at pos and Mtr Size t (src/m4/gr_meter.s's layout)."""
    xs, ys = range(318), range(240)
    if pos == 'Top':
        ys = range(240 - t, 240)
    if pos == 'Bottom':
        ys = range(t)
    if pos == 'Left':
        xs = range(t)
    if pos == 'Right':
        xs = range(320 - t, 320)
    if pos == 'Middle':
        ys = range(118 + (t + 1) // 2 - t, 118 + (t + 1) // 2)
    return {(x, y) for x in xs for y in ys}


def label_pixels(text, x):
    out = set()
    for k, c in enumerate(text):
        for r, row in enumerate(GLYPHS[c]):
            for col, bit in enumerate(row):
                if bit == '1':
                    out |= {(x + 8 * k + 2 * col + dx, 154 - 2 * r + dy) for dx in (0, 1) for dy in (0, 1)}
    return out


_code = {}


class Display:
    """exp_display.s in the M4: FILL and TEXT draw into self.px (TEXT as the box its digits' pixels take), GET_VALUE answers from
    self.settings (unset: no value, so the defaults), two view lists show the Home view and the top view, and self.relayouts
    keeps the arguments of each call of the Home layout."""

    def __init__(self, m4emu, with_gr=False):
        key = 'gr' if with_gr else 'plain'
        if key not in _code:
            _code[key] = m4emu.assemble(ed.MODULE, features.load(), setting_ids.by_name(), inc=exp_inc(GR_DATA if with_gr else 0))
        code, self.sym = _code[key]
        m = self.m = m4emu.M4(code, MOD)
        self.settings, self.px, self.texts, self.fills, self.locked, self.relayouts = {}, {}, [], [], 0, []
        m.stub(GET_VALUE, self.get_value)
        m.stub(FILL, self.fill)
        m.stub(TEXT, self.text)
        m.stub(LOCK, lambda m: setattr(self, 'locked', self.locked + 1))
        m.stub(UNLOCK, lambda m: setattr(self, 'locked', self.locked - 1))
        m.stub(REDRAW)
        m.stub(RELAYOUT, self.relayout)
        self.lists(HOME, TOP)
        self.jacks()

    def get_value(self, m):
        vid = m.reg('r0')
        if vid in self.settings:
            m.write(m.reg('r1'), struct.pack('<II', 2, self.settings[vid]))
            m.reg('r0', 0)
        else:
            m.reg('r0', -3)

    def relayout(self, m):
        assert m.reg('sp') % 8 == 0
        self.relayouts.append((m.reg('r0'), m.reg('r1')))

    def fill(self, m):
        x, y, w = m.reg('r1'), m.reg('r2'), m.reg('r3')
        h, colour, anchor = m.stack_args(3)
        assert m.reg('r0') == FB and anchor == 0 and m.reg('sp') % 8 == 0 and 0 < w <= 320 and 0 < h <= 240, (x, y, w, h)
        self.fills.append((x, y, w, h, colour))
        self.px.update({(i, j): colour for i in range(x, x + w) for j in range(y, y + h)})

    def text(self, m):
        s = m.read(m.reg('r1'), 8).split(b'\0')[0].decode()
        x, (y, number, colour, anchor, mode) = m.reg('r3'), m.stack_args(5)
        assert m.reg('r0') == FB and m.reg('r2') == len(s) and self.locked == 1, 'NUL-terminated, under the widget lock'
        assert m.reg('sp') % 8 == 0
        font = {f.number: f for f in (BIG, SMALL)}[number]
        self.texts.append((s, x, y, number, colour, anchor, mode))
        self.px.update({(i, j): colour for i in range(x, x + width(s, font)) for j in range(y + font.ink[0], y + font.ink[1] + 1)})

    def lists(self, a, b, bank=0):
        self.m.write(NODES, struct.pack('<6I', 1, 1, 0, a, 0, 0))
        self.m.write(NODES + 0x20, struct.pack('<6I', 1, 1, 0, b, 0, 0))
        self.m.u32(LIST_A, NODES)
        self.m.u32(LIST_B, NODES + 0x20)
        self.m.u8(TOP + 9, bank)

    def jacks(self, tip=1, ring=1, tip_mode=0, ring_mode=0):
        for at, v in ((JACKS, ring_mode), (JACKS + 1, tip_mode), (JACKS + 0x22, tip), (JACKS + 0x36, ring)):
            self.m.u8(at, v)

    def pedal(self, jack, x):
        self.m.u32(PEDALS + 0x14 * jack + 8, f2u(x))

    def toggle(self, state):
        self.m.u8(TOGGLE, state)

    def label_widgets(self, shown):
        """The Home view's footswitch label widgets (a text one's visible byte at +0x2a and node at +0x2c, an image's at +0x1d and
        +0x20), those in shown visible, every node clean."""
        for k, w in enumerate(TEXT_WIDGETS + IMAGE_WIDGETS):
            visible, node = (0x2a, 0x2c) if w in TEXT_WIDGETS else (0x1d, 0x20)
            self.m.u8(w + visible, int(w in shown))
            self.m.u32(w + node, WIDGET_NODES + 0x28 * k)
            self.m.u8(WIDGET_NODES + 0x28 * k + 0x24, 0)

    def dirty_labels(self):
        """The label widgets whose node says the next stock paint draws them."""
        return {w for k, w in enumerate(TEXT_WIDGETS + IMAGE_WIDGETS) if self.m.read(WIDGET_NODES + 0x28 * k + 0x24, 1)[0]}

    def gr(self, pos=None, t=20):
        self.m.u32(GR_DATA + gr.SHOWN, 0 if pos is None else 1)
        self.m.u32(GR_DATA + gr.LAYOUT, 0 if pos is None else 1 << 31 | t << 24 | POSITIONS[pos] << 8 | 3)

    def call(self, sym, *args):
        self.m.log.clear()
        return self.m.call(MOD + self.sym[sym], *args)

    def word(self, off, value=None):
        return self.m.u32(MOD + self.sym['exp_data'] + off, value)

    def event(self, ch, x, learn=0):
        self.m.u8(LEARN, learn)
        self.m.write(EV, bytes([6, ch, 0, 0]) + struct.pack('<f', x))
        self.call('exp_event', EV, 0)

    def redrive(self, ctl, x):
        """The preset load's call of the controller setter for controller ctl (1 EXP 1, 2 EXP 2), as its after-handler sees it."""
        self.call('exp_redrive', CTRLS, ctl, 0, f2u(x))

    def ticks(self, n):
        """n ticks of the LED task -> the ones (counting from 1) that asked for a repaint."""
        out = []
        for i in range(n):
            self.call('exp_tick', 1000, 0)
            assert all(regs[:2] == (0, 1) for regs in self.m.calls(REDRAW)), 'the request the layout code ends with'
            if self.m.calls(REDRAW):
                out.append(i + 1)
        return out

    def paint(self, top=False, **settings):
        """A paint of the Home view (or the top view) as its shared hook runs the handlers: before, the stock paint, after."""
        self.settings.update({IDS[k]: v for k, v in settings.items()})
        self.texts, self.fills, self.relayouts = [], [], []
        which, view = ('top', TOP) if top else ('home', HOME)
        self.call(f'exp_{which}_before', FB, view)
        self.call(f'exp_{which}_after', FB, view)
        return self

    def at(self, xs, ys):
        return {(x, y): self.px.get((x, y), 0) for x in xs for y in ys}

    def drawn(self):
        return {k for k, v in self.px.items() if v}


