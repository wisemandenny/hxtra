def test_event_caches_the_controllers_value_and_time(d):
    d.word(MS, 1234)
    d.event(0, 0.63)
    assert d.word(VAL) == f2u(0.63) | 1 << 31 and d.word(STAMP) == 1234 and d.word(DIRTY) == 1
    d.word(MS, 1300)
    d.event(1, 0.25)
    assert d.word(VAL + 4) == f2u(0.25) | 1 << 31 and d.word(STAMP + 4) == 1300
    assert d.word(VAL) == f2u(0.63) | 1 << 31, 'per controller'
    assert not d.m.log, 'plain stores: no call, no lock'


def test_event_ignores_other_controllers_and_learn(d):
    d.event(2, 0.5)
    d.event(6, 0.5)
    d.event(0, 0.5, learn=1)
    assert (d.word(VAL), d.word(VAL + 4), d.word(DIRTY)) == (0, 0, 0)


def test_event_minus_zero_reads_as_zero(d):
    d.jacks(tip=0, ring=0)
    d.event(0, -0.0)
    assert d.word(VAL) == 1 << 31
    d.paint()
    assert ('0', 1, cell(BIG), BIG.number, RED, 0, 1) in d.texts


def test_redrive_caches_the_value_as_no_event(d):
    """A preset's re-drive under EXP Position Global (0x28de12ba EXP 1, 0x28de1282 EXP 2) sets the controller without an event:
    the value as the parameters got it, stamped 3 s old, so it makes no side live by itself."""
    d.word(MS, 5000)
    d.redrive(1, 0.3)
    d.redrive(2, 0.8)
    assert (d.word(VAL), d.word(VAL + 4)) == (f2u(0.3) | 1 << 31, f2u(0.8) | 1 << 31)
    assert (d.word(STAMP), d.word(STAMP + 4), d.word(DIRTY)) == (2000, 2000, 1)
    d.word(DIRTY, 0)
    for ctl in (0, 3, 8):
        d.redrive(ctl, 0.5)
        assert not d.m.log, 'plain stores: no call, no lock'
    assert d.word(DIRTY) == 0 and d.word(VAL) == f2u(0.3) | 1 << 31


