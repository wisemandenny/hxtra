MOD, FB, EV, NODES, GR_DATA = 0x28e80000, 0x28d1ce98, 0x28e70000, 0x28e71000, 0x28e7f000
REDRAW, GET_VALUE, FILL, TEXT, LOCK, UNLOCK = 0x28db8508, 0x28e1f844, 0x100017e8, 0x28db7aa4, 0x28e24970, 0x28e24ae8
RELAYOUT, CTRLS = 0x28dc87cc, 0x28125d30
JACKS, PEDALS, TOGGLE, LEARN = 0x281f5d88, 0x281f5d98, 0x28128a6c, 0x281281e8
LIST_A, LIST_B, HOME, TOP, ALERT = 0x281f35b8, 0x281f3d2c, 0x2812a05c, 0x2812aae0, 0x28124074
RED, GREEN, GREY, TRACK, TICK = 0xff0000, 0x43ff40, 0x666666, 0x2b2b2b, 0x505050
IDS = {'left': 0xe9, 'right': 0xea}
POSITION_IDS = (0x42, 0x47)                                 # EXP 1 and EXP 2 Position: 0 Snapsht, 1 Preset, 2 Global
