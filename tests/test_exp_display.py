@pytest.mark.firmware
def test_the_value_fonts_are_measured_from_the_stock_entries():
    """hx28_boldFont's digits' and '-''s pixels fill rows 5..25 of its 28 px cell, hx21_regularFont's (the smallest stock ASCII font)
    rows 4..19 of 21: under the label's 146..155 the big value takes rows 124..144 and the small one 129..144, and "100" in the big
    one, 44 px, sets the box's width."""
    e7, e8 = stock_entry(7), stock_entry(8)
    assert ed.metrics(e7, e8, b'hx28_boldFont') == (BIG.widths, BIG.spacing, BIG.ink)
    assert ed.metrics(e7, e8, b'hx21_regularFont') == (SMALL.widths, SMALL.spacing, SMALL.ink)
